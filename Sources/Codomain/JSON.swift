import Foundation

/// One thing wrong with one decoded value (JSON, property list, XML, …).
public enum DecodeProblem<F: Error>: Error {
    /// The value has the right type but breaks a rule.
    case rule(F)
    /// A required key is absent or `null`.
    case missing
    /// The value has the wrong JSON type, e.g. a number where a string is expected.
    case wrongType(expected: String)
    /// A key the model does not declare; only with `@JSONParsable(..., strict: true)`.
    case unexpected
}

extension DecodeProblem: Equatable where F: Equatable {}

extension DecodeProblem {
    /// Converts a rule failure; `missing` and `wrongType` stay as they are.
    func map<G>(_ lift: (F) -> G) -> DecodeProblem<G> {
        switch self {
        case .rule(let failure): .rule(lift(failure))
        case .missing: .missing
        case .wrongType(let expected): .wrongType(expected: expected)
        case .unexpected: .unexpected
        }
    }
}

/// A rule failure prints as itself (`blank`), not `rule(MyApp.Failure.blank)`.
extension DecodeProblem: CustomStringConvertible {
    public var description: String {
        switch self {
        case .rule(let failure): "\(failure)"
        case .missing: "missing"
        case .wrongType(let expected): #"wrongType(expected: "\#(expected)")"#
        case .unexpected: "unexpected"
        }
    }
}

/// Why `decode(json:)` or `decode(_:using:)` failed: the decoder could not read the bytes, or the values have
/// problems (all of them, with paths).
public enum DecodeFailure<F: Error>: Error {
    case unreadable(DecodingError)
    case invalid(Issues<DecodeProblem<F>>)
}

/// Reads itself from a `Decoder`, reporting every problem instead of stopping at the first.
public protocol JSONReadable {
    associatedtype Failure: Error
    static func read(from decoder: any Decoder) -> Result<Self, Issues<DecodeProblem<Failure>>>
    /// Reads the value under `key`. The default calls `read(from:)`; `Array` overrides it so XMLCoder sees a sequence.
    static func read<K: CodingKey>(_ container: KeyedDecodingContainer<K>, key: K) throws -> Result<
        Self, Issues<DecodeProblem<Failure>>
    >
}

extension JSONReadable {
    public static func read<K: CodingKey>(_ container: KeyedDecodingContainer<K>, key: K) throws
        -> Result<Self, Issues<DecodeProblem<Failure>>>
    {
        try container.decode(Root<Self>.self, forKey: key).result
    }
}

/// A `Parsable` that also reads and writes JSON. Conformance is generated by `@JSONParsable`.
public protocol JSONParsable: Parsable, JSONReadable where Input: Codable {}

/// Any decoder that turns `Data` into a `Decodable`. `JSONDecoder` and `PropertyListDecoder` conform;
/// add others in one line, e.g. `extension XMLDecoder: DataDecoder {}`.
public protocol DataDecoder {
    func decode<T: Decodable>(_ type: T.Type, from data: Data) throws -> T
}

extension JSONDecoder: DataDecoder {}
extension PropertyListDecoder: DataDecoder {}

extension JSONParsable {
    public static func decode(json: Data) -> Result<Self, DecodeFailure<Failure>> {
        decode(json, using: JSONDecoder())
    }

    /// Reads every key and reports every problem, like `decode(json:)`, with any decoder.
    /// An error that is not a `DecodingError` becomes `.unreadable(.dataCorrupted)` with it as `underlyingError`.
    public static func decode(_ data: Data, using decoder: some DataDecoder) -> Result<
        Self, DecodeFailure<Failure>
    > {
        do {
            return try decoder.decode(Root<Self>.self, from: data).result.mapError(DecodeFailure.invalid)
        } catch let error as DecodingError {
            return .failure(.unreadable(error))
        } catch {
            return .failure(
                .unreadable(
                    .dataCorrupted(
                        .init(codingPath: [], debugDescription: "\(error)", underlyingError: error))))
        }
    }

    /// Sorted keys, so equal values give equal bytes.
    public func json() throws(EncodingError) -> Data {
        let encoder = JSONEncoder()
        encoder.outputFormatting = [.sortedKeys]
        do { return try encoder.encode(encoded) } catch { throw error as! EncodingError }
    }
}

/// Runs `read` inside `init(from:)`. Keys are read with `decode(_:forKey:)`, not `superDecoder(forKey:)`:
/// XMLCoder's `superDecoder(forKey:)` sees only the first of repeated elements.
private struct Root<T: JSONReadable>: Decodable {
    let result: Result<T, Issues<DecodeProblem<T.Failure>>>
    init(from decoder: any Decoder) { result = T.read(from: decoder) }
}

private struct OptionalRoot<T: OptionalField>: Decodable {
    let result: Result<T?, Issues<DecodeProblem<T.Failure>>>
    init(from decoder: any Decoder) { result = T.read(from: decoder) }
}

// MARK: - Fields and arrays

extension Field {
    public static func read(from decoder: any Decoder) -> Result<Self, Issues<DecodeProblem<Failure>>> {
        readInput(Input.self, decoder).flatMap {
            schema.runAll($0).mapError { Issues($0.all.map { .init(path: "", failure: .rule($0)) }) }
        }
    }
}

extension OptionalField {
    public static func read(from decoder: any Decoder) -> Result<Self?, Issues<DecodeProblem<Failure>>> {
        readInput(Input.self, decoder).flatMap {
            schema.runAll($0).mapError { Issues($0.all.map { .init(path: "", failure: .rule($0)) }) }
        }
    }
}

/// Every element is read; problems are reported as `[index]`.
private protocol AbsentMayBeEmpty {}
extension Array: AbsentMayBeEmpty {}

extension Array: JSONReadable where Element: JSONReadable {
    public static func read(from decoder: any Decoder) -> Result<
        [Element], Issues<DecodeProblem<Element.Failure>>
    > {
        var container: any UnkeyedDecodingContainer
        do { container = try decoder.unkeyedContainer() } catch {
            return .failure(Issues("", .wrongType(expected: "array")))
        }
        var values: [Element] = []
        var issues: [Issues<DecodeProblem<Element.Failure>>.Issue] = []
        while !container.isAtEnd {
            let path = "[\(container.currentIndex)]"
            let result: Result<Element, Issues<DecodeProblem<Element.Failure>>>
            do { result = Element.read(from: try container.superDecoder()) } catch {
                result = .failure(Issues("", .wrongType(expected: "\(Element.self)")))
            }
            switch result {
            case .success(let value): values.append(value)
            case .failure(let failed): issues += failed.prefixed(path)
            }
        }
        return issues.isEmpty ? .success(values) : .failure(Issues(issues))
    }

    /// Decodes `[Root<Element>]`, not `Root<[Element]>`: XMLCoder collects repeated elements only for sequence types.
    public static func read<K: CodingKey>(_ container: KeyedDecodingContainer<K>, key: K) throws
        -> Result<[Element], Issues<DecodeProblem<Element.Failure>>>
    {
        let roots: [Root<Element>]
        do { roots = try container.decode([Root<Element>].self, forKey: key) } catch DecodingError
            .typeMismatch
        {
            return .failure(Issues("", .wrongType(expected: "array")))
        }
        var values: [Element] = []
        var issues: [Issues<DecodeProblem<Element.Failure>>.Issue] = []
        for (index, root) in roots.enumerated() {
            switch root.result {
            case .success(let value): values.append(value)
            case .failure(let failed): issues += failed.prefixed("[\(index)]")
            }
        }
        return issues.isEmpty ? .success(values) : .failure(Issues(issues))
    }
}

/// Every value is read; problems are reported as `["key"]`, in key order.
extension Dictionary: JSONReadable where Key == String, Value: JSONReadable {
    public static func read(from decoder: any Decoder) -> Result<
        [String: Value], Issues<DecodeProblem<Value.Failure>>
    > {
        let container: KeyedDecodingContainer<AnyKey>
        do { container = try decoder.container(keyedBy: AnyKey.self) } catch {
            return .failure(Issues("", .wrongType(expected: "object")))
        }
        var values: [String: Value] = [:]
        var issues: [Issues<DecodeProblem<Value.Failure>>.Issue] = []
        for key in container.allKeys.sorted(by: { $0.stringValue < $1.stringValue }) {
            let result: Result<Value, Issues<DecodeProblem<Value.Failure>>>
            do { result = try Value.read(container, key: key) } catch {
                result = .failure(Issues("", .missing))
            }
            switch result {
            case .success(let value): values[key.stringValue] = value
            case .failure(let failed): issues += failed.prefixed(keyPath(key.stringValue))
            }
        }
        return issues.isEmpty ? .success(values) : .failure(Issues(issues))
    }
}

/// `Input` is `Decodable` whenever this runs: `@JSONParsable`'s `Input: Codable` holds every field's `Input`.
private func readInput<I, F>(_: I.Type, _ decoder: any Decoder) -> Result<I, Issues<DecodeProblem<F>>> {
    guard let type = I.self as? any Decodable.Type else {
        preconditionFailure("\(I.self) is not Decodable")
    }
    do { return .success(try type.init(from: decoder) as! I) } catch DecodingError.valueNotFound {
        return .failure(Issues("", .missing))
    } catch {
        return .failure(Issues("", .wrongType(expected: "\(I.self)")))
    }
}

// MARK: - Tagged unions

/// Used by `@JSONParsable` enums: the tag and the payload's keys share one JSON object.
public enum JSONUnion<F: Error> {
    /// The tag's value, one of `cases` (any string when `unknown`). Absent or `null` → `missing`;
    /// anything else → `wrongType("a | b")` (`wrongType("string")` when `unknown`).
    public static func tag(
        _ decoder: any Decoder, key: String, cases: [String], unknown: Bool = false
    ) throws(Issues<DecodeProblem<F>>) -> String {
        let container: KeyedDecodingContainer<AnyKey>
        do { container = try decoder.container(keyedBy: AnyKey.self) } catch {
            throw Issues("", .wrongType(expected: "object"))
        }
        guard container.contains(AnyKey(key)), (try? container.decodeNil(forKey: AnyKey(key))) == false
        else {
            throw Issues(key, .missing)
        }
        guard let tag = try? container.decode(String.self, forKey: AnyKey(key)),
            unknown || cases.contains(tag)
        else {
            throw Issues(key, .wrongType(expected: unknown ? "string" : cases.joined(separator: " | ")))
        }
        return tag
    }

    /// The payload, read from the same object; its problems keep their own paths.
    public static func payload<T: JSONParsable>(
        _: T.Type, _ decoder: any Decoder, key: String, lift: (T.Failure) -> F
    ) throws(Issues<DecodeProblem<F>>) -> T {
        switch UnionTag.$keys.withValue(UnionTag.keys.union([key])) { T.read(from: decoder) } {
        case .success(let value): return value
        case .failure(let failed): throw Issues(failed.prefixed("") { $0.map(lift) })
        }
    }
}

// MARK: - Objects

/// The tag keys of the unions whose payload is being read (several when unions nest), so a strict
/// payload accepts them. Cleared for values nested in the payload.
private enum UnionTag {
    @TaskLocal static var keys: Set<String> = []
}

/// Used by `@JSONParsable`'s generated `init(json:)`: reads every key, keeps every problem.
public struct JSONReader<F: Error> {
    private let container: KeyedDecodingContainer<AnyKey>
    private let unionTags = UnionTag.keys
    public private(set) var issues: [Issues<DecodeProblem<F>>.Issue] = []

    public init(_ decoder: any Decoder) throws(Issues<DecodeProblem<F>>) {
        do { container = try decoder.container(keyedBy: AnyKey.self) } catch {
            throw Issues("", .wrongType(expected: "object"))
        }
    }

    /// `nil` when the key is absent, `null`, or its value has problems (recorded, converted with `lift`).
    public mutating func required<T: JSONReadable>(_ key: String, as: T.Type, lift: (T.Failure) -> F)
        -> T?
    {
        // An absent array is decoded anyway: XMLCoder writes `[]` as no element and reads it back as `[]`; JSONDecoder throws.
        guard isPresent(key) || T.self is any AbsentMayBeEmpty.Type else {
            issues.append(.init(path: key, failure: .missing))
            return nil
        }
        return record(key, read(key) { try T.read($0, key: $1) }, lift)
    }

    /// Outer `nil` when the value has problems; absent or `null` → `.some(nil)`.
    public mutating func optional<T: JSONReadable>(_ key: String, as: T.Type, lift: (T.Failure) -> F)
        -> T??
    {
        guard isPresent(key) else { return .some(nil) }
        return record(key, read(key) { try T.read($0, key: $1) }, lift).map { $0 }
    }

    public mutating func optional<T: OptionalField>(_ key: String, as: T.Type, lift: (T.Failure) -> F)
        -> T??
    {
        guard isPresent(key) else { return .some(nil) }
        return record(key, read(key) { try $0.decode(OptionalRoot<T>.self, forKey: $1).result }, lift)
    }

    /// Absent or `null` → `fallback`, parsed like a value that was present.
    public mutating func defaulted<T: JSONReadable & Parsable>(
        _ key: String, _ fallback: T.Input, as: T.Type, lift: (T.Failure) -> F
    ) -> T? {
        guard isPresent(key) else {
            return record(
                key, T.parse(fallback).mapError { Issues($0.prefixed("") { DecodeProblem.rule($0) }) }, lift)
        }
        return record(key, read(key) { try T.read($0, key: $1) }, lift)
    }

    /// For `strict: true`: every key not in `declared` (except enclosing union tags) is `unexpected`.
    public mutating func rejectUndeclared(_ declared: Set<String>) {
        for key in container.allKeys.map(\.stringValue).sorted()
        where !declared.contains(key) && !unionTags.contains(key) {
            issues.append(.init(path: key, failure: .unexpected))
        }
    }

    private func isPresent(_ key: String) -> Bool {
        container.contains(AnyKey(key)) && (try? container.decodeNil(forKey: AnyKey(key))) == false
    }

    /// Values nested in this object are not union payloads, so no tag key is allowed for them.
    private func read<T, G>(
        _ key: String,
        _ decode: (KeyedDecodingContainer<AnyKey>, AnyKey) throws -> Result<T, Issues<DecodeProblem<G>>>
    ) -> Result<T, Issues<DecodeProblem<G>>> {
        do { return try UnionTag.$keys.withValue([]) { try decode(container, AnyKey(key)) } } catch {
            return .failure(Issues("", .missing))
        }
    }

    private mutating func record<T, G>(
        _ key: String, _ result: Result<T, Issues<DecodeProblem<G>>>, _ lift: (G) -> F
    ) -> T? {
        switch result {
        case .success(let value): return value
        case .failure(let failed):
            issues += failed.prefixed(key) { $0.map(lift) }
            return nil
        }
    }

}

/// Any string key; also used by `@JSONParsable` enums for the tag.
public struct AnyKey: CodingKey {
    public let stringValue: String
    public init(_ string: String) { stringValue = string }
    public init?(stringValue: String) { self.stringValue = stringValue }
    public var intValue: Int? { nil }
    public init?(intValue: Int) { nil }
}
